#!/usr/bin/env python3
"""Generate static/images/math-timeline.svg.

The style and the milestones up to 2023 follow the timeline in Leo de Moura's Marktoberdorf 2026
lectures (leodemoura/Marktoberdorf2026, static/images/timeline.svg).

The Mathlib curve is measured from the git histories (scripts/mathlib-lines.txt, produced by
scripts/count-mathlib-lines.sh): all lines of the .lean files, on the first of each month. It
follows Mathlib 3 until SWITCH (the end of the port) and Mathlib 4 afterwards.

Formalizations in other proof assistants before Lean are shown in a muted style; years before
FIRST_YEAR are placed on a short lead-in that is separated from the axis by a break.

Edit EVENTS and run `python3 scripts/math-timeline.py` from the project root. Lanes are assigned
automatically so that boxes and connector lines do not overlap.
"""

from datetime import date as date_cls
from pathlib import Path

FIRST_YEAR, LAST_YEAR = 2012, 2026
WIDTH, HEIGHT = 1280, 760
X0, YEAR_W = 150, 70    # x of the start of FIRST_YEAR, width of one year
X_PRE = 60              # x of the lead-in for events before FIRST_YEAR
AXIS_Y = 440
BOX_W, BOX_H = 150, 46
GAP = 6                 # minimum horizontal gap between boxes in one lane
MAX_SHIFT = BOX_W // 2 - 14  # maximum sideways shift of a box from its marker
MARKER_GAP = 14         # minimum distance between markers; closer ones are nudged apart
# Lanes in order of preference: (distance from the axis to the near edge of the box, above?)
LANES = [(60, True), (50, False), (128, True), (118, False), (196, True), (186, False),
         (264, True), (254, False)]
CURVE_H = 220           # height of the Mathlib curve at its maximum

# Event styles. OTHER: other proof assistants; AI: proofs generated by AI systems.
HI, NORMAL, OTHER, AI = "hi", "normal", "other", "ai"

# Events whose box must go above the axis.
ABOVE = {"FLT project starts"}

# (title, date label, year, month or None, style)
EVENTS = [
    ("Four Colour Theorem", "2005 · Rocq", 2005, None, OTHER),
    ("Feit–Thompson", "2012 · Rocq", 2012, None, OTHER),
    ("Kepler conjecture", "2014 · HOL Light, Isabelle", 2014, 8, OTHER),
    ("Lean 0.1", "June 2014", 2014, 6, NORMAL),
    ("First course @ CMU", "January 2015", 2015, 1, NORMAL),
    ("Mathlib", "July 2017", 2017, 7, HI),
    ("Zulip community", "February 2018", 2018, 2, NORMAL),
    ("LTE challenge", "December 2020", 2020, 12, HI),
    ("LTE main result", "June 2021", 2021, 6, NORMAL),
    ("LTE completed", "July 2022", 2022, 7, HI),
    ("Lean FRO, Mathlib 4", "July 2023", 2023, 7, HI),
    ("PFR conjecture", "December 2023", 2023, 12, HI),
    ("Equational Theories", "September 2024", 2024, 9, NORMAL),
    ("FLT project starts", "October 2024 · ongoing", 2024, 10, HI),
    ("Carleson's theorem", "July 2025", 2025, 7, NORMAL),
    ("FLT (AI)", "September 2026", 2026, 9, AI),
    ("Navier–Stokes (AI)", "September 2026", 2026, 9, AI),
    ("Quasi-Riemann (AI)", "October 2026", 2026, 10, AI),
]

SWITCH = "2023-08-01"     # first sample taken from Mathlib 4 instead of Mathlib 3


def mathlib_lines():
    """Mathlib size in million lines, as (fractional year, value)."""
    data = []
    for line in (Path(__file__).parent / "mathlib-lines.txt").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        version, date, _, lines = line.split()
        if (version == "3") == (date < SWITCH):
            d = date_cls.fromisoformat(date)
            data.append((d.year + (d.timetuple().tm_yday - 1) / 365, int(lines) / 1e6))
    return sorted(data)


MATHLIB = mathlib_lines()
MATHLIB_MAX = MATHLIB[-1][1]


def x_of_year(year):
    return X0 + (year - FIRST_YEAR) * YEAR_W


def x_of(year, month):
    if year < FIRST_YEAR:
        return X_PRE
    frac = 0.5 if month is None else (month - 0.5) / 12
    return x_of_year(year + frac)


def y_of_value(value):
    return AXIS_Y - value / MATHLIB_MAX * CURVE_H


def smooth_path(pts):
    """A monotone cubic spline (Fritsch–Carlson) through `pts`: smooth, without overshoot."""
    n = len(pts)
    h = [pts[i + 1][0] - pts[i][0] for i in range(n - 1)]
    d = [(pts[i + 1][1] - pts[i][1]) / h[i] for i in range(n - 1)]
    m = [d[0]] + [0 if d[i - 1] * d[i] <= 0 else (d[i - 1] + d[i]) / 2
                  for i in range(1, n - 1)] + [d[-1]]
    for i in range(n - 1):
        if d[i] == 0:
            m[i] = m[i + 1] = 0
            continue
        a, b = m[i] / d[i], m[i + 1] / d[i]
        if a * a + b * b > 9:
            t = 3 / (a * a + b * b) ** 0.5
            m[i], m[i + 1] = t * a * d[i], t * b * d[i]
    path = f"M {pts[0][0]:.1f} {pts[0][1]:.1f}"
    for i in range(n - 1):
        (x0, y0), (x1, y1) = pts[i], pts[i + 1]
        path += (f" C {x0 + h[i] / 3:.1f} {y0 + m[i] * h[i] / 3:.1f}"
                 f" {x1 - h[i] / 3:.1f} {y1 - m[i + 1] * h[i] / 3:.1f} {x1:.1f} {y1:.1f}")
    return path


def curve(name, color, data, opacity):
    # Quarterly samples (and the latest one) smooth out month-to-month noise.
    data = data[::3] + ([data[-1]] if (len(data) - 1) % 3 else [])
    pts = [(x_of_year(t), y_of_value(v)) for t, v in data]
    line = smooth_path(pts)
    area = f"{line} L {pts[-1][0]:.0f} {AXIS_Y - 2} L {pts[0][0]:.0f} {AXIS_Y - 2} Z"
    return [
        f'<path d="{area}" fill="url(#{name})"/>',
        f'<path d="{line}" fill="none" stroke="{color}" stroke-width="2" opacity="{opacity}"/>',
    ]


def spread(xs):
    """Move markers that are closer than MARKER_GAP apart, keeping each group centered on the
    mean of its true positions. `xs` must be sorted."""
    groups = []
    for x in xs:
        groups.append([x])
        while len(groups) > 1:
            a, b = groups[-2], groups[-1]
            end_a = sum(a) / len(a) + (len(a) - 1) * MARKER_GAP / 2
            start_b = sum(b) / len(b) - (len(b) - 1) * MARKER_GAP / 2
            if start_b - end_a >= MARKER_GAP:
                break
            groups[-2:] = [a + b]
    result = []
    for g in groups:
        start = sum(g) / len(g) - (len(g) - 1) * MARKER_GAP / 2
        result += [round(start + i * MARKER_GAP) for i in range(len(g))]
    return result


def assign_lanes(xs, pinned):
    """Greedily place each event in the first lane where its box and connector are free.

    A box may be shifted sideways from its marker by up to MAX_SHIFT; the connector stays vertical
    and still meets the box. Events with pinned[k] set go above the axis. Returns (lane index, box
    center) for each event.
    """
    placed = []  # (marker x, box center, lane index)

    def free(x, c, lane):
        dist, above = LANES[lane]
        if c - BOX_W / 2 < 2 or c + BOX_W / 2 > WIDTH - 2:
            return False
        # Keep clear of the end of the Mathlib curve and its "2.2M" label.
        top = AXIS_Y - dist - BOX_H if above else AXIS_Y + dist
        x1, y1 = x_of_year(MATHLIB[-1][0]), y_of_value(MATHLIB[-1][1])
        if (c - BOX_W / 2 < x1 + 6 and c + BOX_W / 2 > x1 - 40
                and top < y1 + 6 and top + BOX_H > y1 - 20):
            return False
        for x2, c2, lane2 in placed:
            dist2, above2 = LANES[lane2]
            if above2 != above:
                continue
            if lane2 == lane and abs(c - c2) < BOX_W + GAP:
                return False
            # Connectors to farther lanes must not cross boxes in nearer lanes.
            if dist2 < dist and abs(x - c2) < BOX_W / 2 + GAP:
                return False
            if dist2 > dist and abs(x2 - c) < BOX_W / 2 + GAP:
                return False
        return True

    shifts = range(-MAX_SHIFT, MAX_SHIFT + 1)
    budget = [200000]

    def options(x, above_only):
        """For each lane: the smallest feasible shift and the leftmost feasible shift."""
        result = []
        for lane in range(len(LANES)):
            if above_only and not LANES[lane][1]:
                continue
            ok = [d for d in shifts if free(x, x + d, lane)]
            if ok:
                for d in {min(ok, key=abs), ok[0]}:
                    result.append((abs(d) + 20 * (lane // 2), lane, d))
        return sorted(result)

    def search(k):
        if k == len(xs):
            return True
        x = xs[k]
        for _, lane, d in options(x, pinned[k]):
            budget[0] -= 1
            if budget[0] < 0:
                return False
            placed.append((x, x + d, lane))
            if search(k + 1):
                return True
            placed.pop()
        return False

    if not search(0):
        raise SystemExit("no layout found; remove events or enlarge the figure")
    return [(lane, c) for _, c, lane in placed]


def svg():
    end = x_of_year(LAST_YEAR + 1) + 10
    out = [
        f'<svg viewBox="0 0 {WIDTH} {HEIGHT}" xmlns="http://www.w3.org/2000/svg" role="img" '
        'font-family="Source Sans 3, sans-serif">',
        '<defs>'
        '<linearGradient id="mlgrad" x1="0" y1="0" x2="0" y2="1">'
        '<stop offset="0%" stop-color="#0891b2" stop-opacity="0.12"/>'
        '<stop offset="100%" stop-color="#0891b2" stop-opacity="0.02"/></linearGradient>'
        '</defs>',
    ]

    # Mathlib curve: Mathlib 3 until the port, then Mathlib 4.
    out += curve("mlgrad", "#0891b2", MATHLIB, 0.5)
    t1, v1 = MATHLIB[-1]
    x1, y1 = x_of_year(t1), y_of_value(v1)
    out.append(f'<circle cx="{x1:.0f}" cy="{y1:.0f}" r="3.5" fill="#0891b2" opacity="0.6"/>')
    out.append(f'<text x="{x1 - 8:.0f}" y="{y1 - 6:.0f}" font-size="13" text-anchor="end" '
               f'fill="#64748b">{v1:.1f}M</text>')
    # The legend goes to the top left; its y coordinates are filled in after cropping.
    legend = [
        ("Mathlib lines of code", '<rect x="{x}" y="{y}" width="18" height="4" rx="2" '
         'fill="#0891b2" opacity="0.7"/>'),
        ("AI-generated proofs", '<rect x="{x}" y="{y_box}" width="18" height="12" rx="3" '
         'fill="#f5f3ff" stroke="#a78bfa" stroke-width="1.5"/>'),
        ("Other proof assistants", '<rect x="{x}" y="{y_box}" width="18" height="12" rx="3" '
         'fill="#fff" stroke="#94a3b8" stroke-width="1.5" stroke-dasharray="3 2"/>'),
    ]
    for i, (label, icon) in enumerate(legend):
        out.append(icon.format(x=X_PRE - 30, y=f"LEGEND_Y{i}", y_box=f"LEGEND_B{i}"))
        out.append(f'<text x="{X_PRE - 4}" y="LEGEND_T{i}" font-size="14" fill="#64748b">'
                   f'{label}</text>')

    # Axis: the lead-in for earlier years, a break, and the main axis.
    out.append(f'<line x1="{X_PRE - 30}" y1="{AXIS_Y}" x2="{X_PRE + 36}" y2="{AXIS_Y}" '
               'stroke="#0891b2" stroke-width="3"/>')
    for dx in (44, 54):
        out.append(f'<line x1="{X_PRE + dx - 4}" y1="{AXIS_Y + 9}" x2="{X_PRE + dx + 4}" '
                   f'y2="{AXIS_Y - 9}" stroke="#0891b2" stroke-width="2"/>')
    out.append(f'<line x1="{X_PRE + 62}" y1="{AXIS_Y}" x2="{end}" y2="{AXIS_Y}" stroke="#0891b2" '
               'stroke-width="3"/>')
    pre_years = sorted({e[2] for e in EVENTS if e[2] < FIRST_YEAR})
    assert len(pre_years) <= 1, "the lead-in has room for one year only"
    for year in pre_years:
        out.append(f'<line x1="{X_PRE}" y1="{AXIS_Y - 6}" x2="{X_PRE}" y2="{AXIS_Y + 6}" '
                   'stroke="#0891b2" stroke-width="2"/>')
        out.append(f'<text x="{X_PRE}" y="{AXIS_Y + 30}" text-anchor="middle" font-size="15" '
                   f'fill="#64748b">{year}</text>')
    out.append(f'<polygon points="{end},{AXIS_Y - 7} {end + 18},{AXIS_Y} {end},{AXIS_Y + 7}" '
               'fill="#0891b2"/>')
    for year in range(FIRST_YEAR, LAST_YEAR + 1):
        x = x_of_year(year)
        out.append(f'<line x1="{x}" y1="{AXIS_Y - 6}" x2="{x}" y2="{AXIS_Y + 6}" '
                   'stroke="#0891b2" stroke-width="2"/>')
        out.append(f'<text x="{x}" y="{AXIS_Y + 30}" text-anchor="middle" font-size="15" '
                   f'fill="#64748b">{year}</text>')

    # Events. Connectors first, so that markers and boxes are drawn on top of them.
    events = sorted(EVENTS, key=lambda e: x_of(e[2], e[3]))
    xs = spread([x_of(e[2], e[3]) for e in events])
    spots = assign_lanes(xs, [e[0] in ABOVE for e in events])
    boxes, markers = [], []
    for (title, date, _, _, style), x, (lane, c) in zip(events, xs, spots):
        dist, above = LANES[lane]
        top = AXIS_Y - dist - BOX_H if above else AXIS_Y + dist
        y2 = top + BOX_H if above else top
        out.append(f'<line x1="{x}" y1="{AXIS_Y}" x2="{x}" y2="{y2}" '
                   f'stroke="{"#94a3b8" if style == HI else "#cbd5e1"}" stroke-width="1.5"/>')
        if style == HI:
            markers.append(f'<circle cx="{x}" cy="{AXIS_Y}" r="8" fill="#0073A3"/>')
            box = 'fill="#fff" stroke="#0073A3" stroke-width="2"'
            fill, weight = "#0073A3", 700
        elif style == AI:
            markers.append(f'<circle cx="{x}" cy="{AXIS_Y}" r="5" fill="#fff" stroke="#8b5cf6" '
                           'stroke-width="2.5"/>')
            box = 'fill="#f5f3ff" stroke="#c4b5fd" stroke-width="1.5"'
            fill, weight = "#0f172a", 600
        elif style == OTHER:
            markers.append(f'<circle cx="{x}" cy="{AXIS_Y}" r="5" fill="#fff" stroke="#94a3b8" '
                           'stroke-width="2.5"/>')
            box = 'fill="#fff" stroke="#94a3b8" stroke-width="1.5" stroke-dasharray="5 4"'
            fill, weight = "#475569", 600
        else:
            markers.append(f'<circle cx="{x}" cy="{AXIS_Y}" r="5" fill="#fff" stroke="#0891b2" '
                           'stroke-width="2.5"/>')
            box = 'fill="#f8fafc" stroke="#e2e8f0"'
            fill, weight = "#0f172a", 600
        boxes.append(f'<rect x="{c - BOX_W // 2}" y="{top}" width="{BOX_W}" height="{BOX_H}" '
                     f'rx="8" {box}/>')
        boxes.append(f'<text x="{c}" y="{top + 20}" text-anchor="middle" font-size="15" '
                     f'font-weight="{weight}" fill="{fill}">{title.replace("&", "&amp;")}</text>')
        boxes.append(f'<text x="{c}" y="{top + 38}" text-anchor="middle" font-size="12" '
                     f'fill="#64748b">{date}</text>')
    out += markers + boxes
    out.append("</svg>")
    # Crop vertically to the content: the legend above the highest box or curve point, and the
    # lowest box below.
    tops = [AXIS_Y - LANES[lane][0] - BOX_H for lane, _ in spots if LANES[lane][1]]
    bottoms = [AXIS_Y + LANES[lane][0] + BOX_H for lane, _ in spots if not LANES[lane][1]]
    y_min = min(tops + [y_of_value(MATHLIB_MAX) - 20, AXIS_Y - 60]) - 92
    y_max = max(bottoms + [AXIS_Y + 40]) + 10
    out[0] = out[0].replace(f'viewBox="0 0 {WIDTH} {HEIGHT}"',
                            f'viewBox="0 {y_min:.0f} {WIDTH} {y_max - y_min:.0f}" '
                            f'width="{WIDTH}" height="{y_max - y_min:.0f}"')
    result = "\n".join(out)
    for i in range(len(legend)):
        t = y_min + 30 + 22 * i
        result = (result.replace(f"LEGEND_Y{i}", f"{t - 6:.0f}")
                  .replace(f"LEGEND_B{i}", f"{t - 11:.0f}")
                  .replace(f"LEGEND_T{i}", f"{t:.0f}"))
    return result + "\n"


if __name__ == "__main__":
    Path("static/images/math-timeline.svg").write_text(svg())
